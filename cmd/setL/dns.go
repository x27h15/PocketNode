var demoDNS = []string{"9.9.9.9", "149.112.112.112"}

func GetCurrentDNS() []string {
	if DemoMode {
		return demoDNS
	}
	data, err := os.ReadFile(ResolvConfPath)
	if err != nil {
		return nil
	}
	var servers []string
	lines := strings.Split(string(data), "\n")
	for _, l := range lines {
		l = strings.TrimSpace(l)
		if strings.HasPrefix(l, "nameserver") {
			parts := strings.Fields(l)
			if len(parts) >= 2 {
				servers = append(servers, parts[1])
			}
		}
	}
	return servers
}

func SetDNS(primary, sec string) error {
	if DemoMode {
		if sec != "" {
			demoDNS = []string{primary, sec}
		} else {
			demoDNS = []string{primary}
		}
		return nil
	}

	var content strings.Builder
	content.WriteString("# Generated by setup-loader\n")
	content.WriteString(fmt.Sprintf("nameserver %s\n", primary))
	if sec != "" {
		content.WriteString(fmt.Sprintf("nameserver %s\n", sec))
	}
	return os.WriteFile(ResolvConfPath, []byte(content.String()), 0644)
}

func TestDNSResolution() {
	fmt.Println("\n" + ColorYellow + "Тестирование разрешения доменных имён..." + ColorReset)
	domains := []string{"deb.debian.org", "google.com", "yandex.ru", "cloudflare.com"}

	for _, d := range domains {
		start := time.Now()
		ctx, cancel := context.WithTimeout(context.Background(), 3*time.Second)
		ips, err := net.DefaultResolver.LookupIP(ctx, "ip4", d)
		cancel()
		elapsed := time.Since(start)

		if err != nil {
			fmt.Printf("  • %-16s : %sОшибка: %v%s\n", d, ColorRed, err, ColorReset)
		} else {
			var ipStrs []string
			for _, ip := range ips {
				ipStrs = append(ipStrs, ip.String())
			}
			fmt.Printf("  • %-16s : %s%s%s %s(%d ms)%s\n",
				d, ColorGreen, strings.Join(ipStrs, ", "), ColorReset, ColorGray, elapsed.Milliseconds(), ColorReset)
		}
	}
}

